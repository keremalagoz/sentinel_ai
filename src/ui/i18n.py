# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def set_language(lang: str) -> None:
    """Set the active UI language. Falls back to 'en' if unknown."""
    global _current_lang
    _current_lang = lang if lang in _TRANSLATIONS else "en"


def get_language() -> str:
    """Return the current language code."""
    return _current_lang


def t(key: str) -> str:
    """Translate *key* using the active language, with English fallback."""
    lang_dict = _TRANSLATIONS.get(_current_lang, _EN)
    value = lang_dict.get(key)
    if value is not None:
        return value
    return _EN.get(key, key)


def get_available_languages() -> tuple:
    """Return tuple of (code, native_name) for all supported languages."""
    return LANGUAGES
